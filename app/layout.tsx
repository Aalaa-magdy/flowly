import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import { MuiThemeProvider } from "./mui-theme-provider";
import { ThemeProvider } from "./theme-provider";
import { THEME_STORAGE_KEY } from "./theme-config";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

// Runs while the HTML is parsed, before first paint, so the saved theme is
// applied without a flash. Falls back to the OS preference when unset.
const themeInitScript = `(function(){try{var m=localStorage.getItem("${THEME_STORAGE_KEY}");var d=window.matchMedia("(prefers-color-scheme: dark)").matches;var t=(m==="light"||m==="dark")?m:(d?"dark":"light");document.documentElement.setAttribute("data-theme",t)}catch(e){}})()`;

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      data-theme="light"
      suppressHydrationWarning
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <head>
        <script dangerouslySetInnerHTML={{ __html: themeInitScript }} />
      </head>
      <body className="min-h-full flex flex-col">
        <ThemeProvider>
          <MuiThemeProvider>{children}</MuiThemeProvider>
        </ThemeProvider>
      </body>
    </html>
  );
}
